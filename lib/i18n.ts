export function getCategoryName(categoryId: string, lang: Language): string {
  const map: Record<string, TranslationKey> = {
    food: 'catFood',
    transport: 'catTransport',
    bills: 'catBills',
    shopping: 'catShopping',
    health: 'catHealth',
    education: 'catEducation',
    entertainment: 'catEntertainment',
    rent: 'catRent',
    phone: 'catPhone',
    clothes: 'catClothes',
    other_expense: 'catOther',
    salary: 'catSalary',
    freelance: 'catFreelance',
    investment: 'catInvestment',
    gift: 'catGift',
    bonus: 'catBonus',
    jameya_savings: 'catJameyaSavings',
    debt_loan: 'catDebtLoan',
    other_income: 'catOther',
  };
  const key = map[categoryId];
  if (key) return translations[lang][key] as string;

  // Check custom category in memory/storage
  try {
    const { getCategoryById } = require('./categories');
    const customCat = getCategoryById(categoryId);
    if (customCat) {
      if (lang === 'ar') {
        return customCat.nameAr || customCat.name || categoryId;
      } else if (lang === 'hi') {
        return customCat.nameHi || customCat.name || categoryId;
      } else {
        return customCat.name || customCat.nameAr || categoryId;
      }
    }
  } catch (e) {
    console.error('Error fetching custom category name:', e);
  }

  return categoryId;
}

