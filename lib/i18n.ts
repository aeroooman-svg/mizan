export function getCurrencyName(code: string, lang: Language): string {
  const map: Record<string, TranslationKey> = {
    EGP: 'egp',
    KWD: 'kwd',
    USD: 'usd',
    SAR: 'sar',
    AED: 'aed',
    EUR: 'eur',
    GBP: 'gbp',
    QAR: 'qar',
    BHD: 'bhd',
    OMR: 'omr',
    INR: 'inr',
  };
  const key = map[code];
  if (key) return translations[lang][key] as string;
  return code;
}

export function formatDateLocalized(dateStr: string, lang: Language): string {
  const date = new Date(dateStr);
  const t = translations[lang];
  const hours = date.getHours();
  const minutes = date.getMinutes();
  const period = lang === 'ar' ? (hours >= 12 ? 'م' : 'ص') : (hours >= 12 ? 'PM' : 'AM');
  const h12 = hours % 12 || 12;
  const mm = minutes.toString().padStart(2, '0');
  return `${date.getDate()} ${t.months[date.getMonth()]} ${date.getFullYear()} · ${h12}:${mm} ${period}`;
}
